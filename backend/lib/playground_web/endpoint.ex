defmodule PlaygroundWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :playground

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_playground_key",
    signing_salt: "cQPle66A",
    same_site: "Lax"
  ]

  # Live sessions' relay (PlaygroundWeb.LiveSocket). A frame holds a
  # message of up to :max_message bytes and Phoenix's framing.
  socket "/socket", PlaygroundWeb.LiveSocket,
    websocket: [max_frame_size: 1_048_576],
    longpoll: false

  # The TCP relay (PlaygroundWeb.RelaySocket): opened by projects' exec
  # frames, on the usercontent domain (:relay_origins). A frame holds a
  # kind, an id and up to Playground.Relay's :max_payload bytes; Bandit
  # counts the WebSocket header too (14 bytes for a masked frame over
  # 65_535).
  socket "/relay", PlaygroundWeb.RelaySocket,
    websocket: [
      path: "",
      max_frame_size: 65_536 + 5 + 14,
      check_origin: {PlaygroundWeb.RelaySocket, :origin_allowed?, []}
    ],
    longpoll: false

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :playground,
    gzip: not code_reloading?,
    only: PlaygroundWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :playground
  end

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug PlaygroundWeb.Router
end
